-- ============ NON-GRADED -> GRADED (level change history) ============
-- A SNEd learner remains non-graded year after year. Moving to a graded level needs the
-- SPED assessment form and approval from the Schools Division Office (SDO), per LIS guidance.
CREATE TABLE learner_level_changes (
  id                  SERIAL PRIMARY KEY,
  learner_id          UUID NOT NULL REFERENCES learners(id) ON DELETE CASCADE,
  from_level          TEXT NOT NULL,   -- 'non_graded'
  to_level            TEXT NOT NULL,   -- e.g. 'Grade 1'
  proposed_on         DATE NOT NULL,
  sped_assessment_file TEXT,           -- the SPED assessment form
  sdo_status          TEXT NOT NULL DEFAULT 'not_submitted'
                      CHECK (sdo_status IN ('not_submitted','submitted','approved','denied')),
  sdo_decision_on     DATE,
  lis_updated         BOOLEAN DEFAULT FALSE,
  notes               TEXT
);

-- ============ HEALTH & NUTRITION (SF8-style) ============
-- DepEd nutritional status uses height and weight to get BMI-for-age and height-for-age,
-- recorded as baseline (start of year) and endline (end of year).
CREATE TABLE health_measurements (
  id             SERIAL PRIMARY KEY,
  learner_id     UUID NOT NULL REFERENCES learners(id) ON DELETE CASCADE,
  school_year_id INT NOT NULL REFERENCES school_years(id),
  period         TEXT NOT NULL CHECK (period IN ('baseline','endline','other')),
  measured_on    DATE NOT NULL,
  height_cm      NUMERIC(5,1) NOT NULL,
  weight_kg      NUMERIC(5,1) NOT NULL,
  bmi            NUMERIC(4,1) GENERATED ALWAYS AS (round(weight_kg / ((height_cm/100.0)*(height_cm/100.0)), 1)) STORED,
  -- Categories use WHO growth standards by age and sex: compute in the app from the WHO tables.
  bmi_category   TEXT CHECK (bmi_category IN ('severely_wasted','wasted','normal','overweight','obese')),
  hfa_category   TEXT CHECK (hfa_category IN ('severely_stunted','stunted','normal','tall')),
  measured_by    UUID REFERENCES users(id),
  notes          TEXT,
  UNIQUE (learner_id, school_year_id, period)
);

