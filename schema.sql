-- ============ "NEEDS ATTENTION" VIEW ============
CREATE VIEW needs_attention AS
SELECT l.id AS learner_id, l.first_name, l.last_name, 'IEP review overdue' AS reason
FROM learners l JOIN ieps i ON i.learner_id = l.id
WHERE i.status = 'active' AND i.next_review_date < CURRENT_DATE
UNION ALL
SELECT l.id, l.first_name, l.last_name, 'No progress entry in 30 days'
FROM learners l
WHERE l.status = 'enrolled' AND NOT EXISTS (
  SELECT 1 FROM ieps i
  JOIN iep_goals g ON g.iep_id = i.id
  JOIN iep_objectives o ON o.goal_id = g.id
  JOIN progress_entries p ON p.objective_id = o.id
  WHERE i.learner_id = l.id AND i.status = 'active'
    AND p.recorded_on > CURRENT_DATE - INTERVAL '30 days'
);
