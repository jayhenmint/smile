-- SMILE (Student Monitoring for Inclusive Learning Education): PostgreSQL schema (MVP)
-- Verify field names against current DepEd forms (LIS, SF2, SF9, SF10) before production use.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ============ SCHOOLS (multi-school ready) ============
-- Every school-owned table carries school_id so another school can adopt the tool
-- without seeing your data. Enforce it in Laravel with a global scope + policies
-- (or Postgres Row Level Security).
CREATE TABLE schools (
  id             SERIAL PRIMARY KEY,
  deped_school_id TEXT UNIQUE,         -- DepEd 6-digit school ID
  name           TEXT NOT NULL,
  division       TEXT,
  region         TEXT,
  address        TEXT,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============ USERS & ACCESS ============
-- system_admin: developer/operator, technical settings only (no routine access to learner data)
-- school_admin: principal, SPED coordinator, or (for a one-teacher school) the teacher
-- sped_teacher: adviser of a section; adviser status comes from sections.adviser_id
CREATE TABLE users (
  id            UUID PRIMARY KEY,           -- generated by Laravel HasUuids
  school_id     INT REFERENCES schools(id) ON DELETE RESTRICT, -- NULL for global system_admin or parents linked via learners
  email         TEXT UNIQUE NOT NULL,
  password      TEXT NOT NULL,               -- Laravel's hashed password cast
  name          TEXT NOT NULL,               -- Laravel auth / Inertia convention
  email_verified_at TIMESTAMPTZ,
  remember_token VARCHAR(100),
  phone         TEXT,
  is_active     BOOLEAN NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ
);
CREATE INDEX users_school_id_index ON users(school_id);
CREATE UNIQUE INDEX users_school_id_id_unique ON users(school_id, id);

-- A user can hold several roles, e.g. the only teacher is both sped_teacher and school_admin.
-- Use Spatie's standard tables instead of a parallel user_roles enum/table.
-- Definitions are global framework metadata, not school-owned learner data.
-- Roles: system_admin, school_admin, sped_teacher, regular_teacher, parent.
-- principal is optional and is not seeded until requested.
CREATE TABLE roles (
  id BIGSERIAL PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  guard_name VARCHAR(255) NOT NULL,
  created_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ,
  UNIQUE (name, guard_name)
);
CREATE TABLE permissions (
  id BIGSERIAL PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  guard_name VARCHAR(255) NOT NULL,
  created_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ,
  UNIQUE (name, guard_name)
);
CREATE TABLE model_has_roles (
  role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
  model_type VARCHAR(255) NOT NULL,
  model_id UUID NOT NULL,
  PRIMARY KEY (role_id, model_id, model_type)
);
CREATE INDEX model_has_roles_model_id_model_type_index ON model_has_roles(model_id, model_type);
CREATE TABLE model_has_permissions (
  permission_id BIGINT NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
  model_type VARCHAR(255) NOT NULL,
  model_id UUID NOT NULL,
  PRIMARY KEY (permission_id, model_id, model_type)
);
CREATE INDEX model_has_permissions_model_id_model_type_index ON model_has_permissions(model_id, model_type);
CREATE TABLE role_has_permissions (
  permission_id BIGINT NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
  role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
  PRIMARY KEY (permission_id, role_id)
);

-- ============ SCHOOL STRUCTURE ============
CREATE TABLE school_years (
  id         SERIAL PRIMARY KEY,
  school_id  INT NOT NULL REFERENCES schools(id),
  label      TEXT NOT NULL,            -- e.g. '2026-2027'
  start_date DATE NOT NULL,
  end_date   DATE NOT NULL,
  is_current BOOLEAN NOT NULL DEFAULT FALSE,
  UNIQUE (school_id, label)           -- prevent duplicate year labels within one school
);
-- At most one manually selected current year per school; no automatic enrollment/promotion.
CREATE UNIQUE INDEX school_years_one_current_per_school ON school_years(school_id) WHERE is_current;
CREATE UNIQUE INDEX school_years_school_id_id_unique ON school_years(school_id, id);

CREATE TABLE sections (
  id             SERIAL PRIMARY KEY,
  school_id      INT NOT NULL REFERENCES schools(id),
  school_year_id INT NOT NULL,
  grade_level    TEXT NOT NULL DEFAULT 'Non-graded', -- no automatic graded-level assignment
  name           TEXT NOT NULL,
  placement_type TEXT NOT NULL DEFAULT 'sped_self_contained' CHECK (placement_type IN ('sped_self_contained','resource_room','regular')),
  adviser_id     UUID,   -- the class adviser: sees only this section's learners
  UNIQUE (school_id, school_year_id, name),
  UNIQUE (school_id, id),
  UNIQUE (school_id, school_year_id, id),
  FOREIGN KEY (school_id, school_year_id) REFERENCES school_years(school_id, id) ON DELETE RESTRICT,
  FOREIGN KEY (school_id, adviser_id) REFERENCES users(school_id, id) ON DELETE RESTRICT
);

-- Co-teachers, aides, and subject teachers who may also view/log progress for a section
CREATE TABLE section_teachers (
  school_id  INT NOT NULL REFERENCES schools(id),
  section_id INT NOT NULL,
  user_id    UUID NOT NULL,
  role       TEXT NOT NULL DEFAULT 'co_teacher' CHECK (role IN ('adviser','co_teacher','aide','therapist')),
  PRIMARY KEY (section_id, user_id),
  FOREIGN KEY (school_id, section_id) REFERENCES sections(school_id, id) ON DELETE CASCADE,
  FOREIGN KEY (school_id, user_id) REFERENCES users(school_id, id) ON DELETE CASCADE
);

-- ============ GLOBAL SMILE ID RESERVATIONS ============
-- Technical identifier namespace: no school_id, learner link, or personal data.
-- Retain every issued ID permanently, even if a learner record is later removed.
-- Allocate inside the learner-creation transaction; retry primary-key collisions.
CREATE TABLE smile_id_reservations (
  smile_id VARCHAR(11) PRIMARY KEY CHECK (smile_id ~ '^SM-[A-HJ-NP-Z2-9]{8}$')
);
CREATE OR REPLACE FUNCTION prevent_smile_id_reservation_change() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'Reserved SMILE IDs cannot be changed or removed';
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER smile_id_reservations_immutable
  BEFORE UPDATE OR DELETE ON smile_id_reservations
  FOR EACH ROW EXECUTE FUNCTION prevent_smile_id_reservation_change();
CREATE TRIGGER smile_id_reservations_no_truncate
  BEFORE TRUNCATE ON smile_id_reservations
  FOR EACH STATEMENT EXECUTE FUNCTION prevent_smile_id_reservation_change();

-- ============ LEARNERS ============
CREATE TABLE learners (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  school_id       INT NOT NULL REFERENCES schools(id),   -- school currently responsible for the record
  lrn             TEXT UNIQUE CHECK (lrn ~ '^[0-9]{12}$'),  -- DepEd LRN: unique, permanent, 12 digits,
                                       -- issued through the LIS; stays with the learner across schools.
                                       -- Nullable: a new learner may be waiting for LRN approval.
  -- SMILE learner ID: generated by the tool, never typed in, never taken from the school.
  -- Globally unique (works across adopting schools), permanent, and never reused.
  -- Random and not built from name, birthdate, or LRN, so it reveals nothing about the learner.
  -- Suggested format: 'SM-' + 8 characters from A-Z (minus I, O) and 2-9, e.g. 'SM-7K3QX9PD'.
  -- Generate it in the app (retry on collision). The unique constraint is the safety net.
  smile_id        VARCHAR(11) NOT NULL UNIQUE REFERENCES smile_id_reservations(smile_id) ON DELETE RESTRICT,
  -- LRN is optional. The SMILE ID identifies the learner when there is no LRN yet.
  lrn_status      TEXT NOT NULL DEFAULT 'pending' CHECK (lrn_status IN ('pending','issued','needs_correction')),
  CHECK (lrn_status <> 'issued' OR lrn IS NOT NULL),   -- 'issued' requires an LRN
  last_name       TEXT NOT NULL,
  first_name      TEXT NOT NULL,
  middle_name     TEXT,
  birthdate       DATE NOT NULL,
  sex             TEXT CHECK (sex IN ('M','F')),
  address         TEXT,
  mother_tongue   TEXT,
  has_pwd_id      BOOLEAN DEFAULT FALSE,
  pwd_id_number   TEXT,
  health_notes    TEXT,                -- allergies, medication (encrypt at app level)
  photo_url       TEXT,
  status          TEXT NOT NULL DEFAULT 'enrolled' CHECK (status IN ('enrolled','transferred_out','dropped','graduated')),
  consent_confirmed_by UUID NOT NULL,
  consent_confirmed_at TIMESTAMPTZ NOT NULL,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (school_id, id),
  FOREIGN KEY (school_id, consent_confirmed_by) REFERENCES users(school_id, id) ON DELETE RESTRICT
);

-- Consent already obtained; signed copy may follow. This records the teacher's
-- confirmation, not the guardian's signed consent record planned for Phase 4.
CREATE OR REPLACE FUNCTION prevent_learner_smile_id_change() RETURNS trigger AS $$
BEGIN
  IF NEW.smile_id IS DISTINCT FROM OLD.smile_id THEN
    RAISE EXCEPTION 'A learner SMILE ID cannot be changed';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER learners_smile_id_immutable BEFORE UPDATE ON learners
  FOR EACH ROW EXECUTE FUNCTION prevent_learner_smile_id_change();

CREATE TABLE guardians (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id      UUID REFERENCES users(id),   -- set if guardian has portal access
  full_name    TEXT NOT NULL,
  relationship TEXT NOT NULL,
  phone        TEXT,
  email        TEXT,
  address      TEXT
);

CREATE TABLE learner_guardians (
  learner_id         UUID REFERENCES learners(id) ON DELETE CASCADE,
  guardian_id        UUID REFERENCES guardians(id) ON DELETE CASCADE,
  is_primary         BOOLEAN DEFAULT FALSE,
  is_emergency       BOOLEAN DEFAULT FALSE,
  PRIMARY KEY (learner_id, guardian_id)
);

-- Duplicate check for learners without an LRN: the app warns (does not block) when the same
-- name and birthdate already exist in the school. This index makes that lookup fast.
CREATE INDEX idx_learner_dup_check ON learners(school_id, lower(last_name), lower(first_name), birthdate);

CREATE TABLE enrollments (
  id             SERIAL PRIMARY KEY,
  school_id      INT NOT NULL REFERENCES schools(id) ON DELETE RESTRICT,
  learner_id     UUID NOT NULL,
  school_year_id INT NOT NULL,
  section_id     INT,
  -- Non-graded learners are re-enrolled every year in the same kind of class.
  -- A learner stays 'non_graded' until a documented, approved level change (see learner_level_changes).
  level_status   TEXT NOT NULL DEFAULT 'non_graded' CHECK (level_status IN ('non_graded','graded')),
  grade_level    TEXT,                 -- only filled when level_status = 'graded'
  lis_enrollment_status TEXT DEFAULT 'pending' CHECK (lis_enrollment_status IN ('pending','encoded','approved')),
  enrolled_on    DATE NOT NULL DEFAULT CURRENT_DATE,
  is_transferee  BOOLEAN DEFAULT FALSE,
  previous_school TEXT,
  UNIQUE (learner_id, school_year_id),
  FOREIGN KEY (school_id, learner_id) REFERENCES learners(school_id, id) ON DELETE RESTRICT,
  FOREIGN KEY (school_id, school_year_id) REFERENCES school_years(school_id, id) ON DELETE RESTRICT,
  FOREIGN KEY (school_id, school_year_id, section_id) REFERENCES sections(school_id, school_year_id, id) ON DELETE RESTRICT,
  -- Phase 1 has no approved level-change workflow. Phase 4 must replace this
  -- safeguard with enforcement of an approved learner_level_changes record.
  CONSTRAINT enrollments_non_graded_only CHECK (level_status = 'non_graded' AND grade_level IS NULL)
);

